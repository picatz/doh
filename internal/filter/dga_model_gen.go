//go:build ignore

// dga_model_gen.go generates dga_model.go, the character bigram model the
// DGA scorer compares labels with, from testdata/dga-train.txt: popular
// domains' registrable labels, and the brand names in brands.go. Run it
// with go generate; the output depends only on its inputs.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"log"
	"math"
	"os"
	"regexp"
	"strings"

	"golang.org/x/net/publicsuffix"
)

// The model's symbols, as dga.go numbers them: a to z, 0 to 9, the
// hyphen, and the boundary before and after a label.
const (
	symbols  = 38
	boundary = 37
)

func symbol(c byte) int {
	switch {
	case c >= 'a' && c <= 'z':
		return int(c - 'a')
	case c >= '0' && c <= '9':
		return 26 + int(c-'0')
	case c == '-':
		return 36
	}
	return -1
}

// smoothing is added to every count (additive smoothing), so transitions
// never seen in training are unlikely, not impossible.
const smoothing = 0.5

func main() {
	var labels []string
	for _, label := range append(corpus("testdata/dga-train.txt"), brandNames("brands.go")...) {
		if usable(label) {
			labels = append(labels, label)
		}
	}

	model := train(labels)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by dga_model_gen.go from %d labels; DO NOT EDIT.\n\n", len(labels))
	b.WriteString("package filter\n\n")
	b.WriteString("// dgaBigram holds log2 P(next | prev) for the model's symbols, indexed\n")
	b.WriteString("// prev*dgaSymbols + next, as dgaSymbol numbers them.\n")
	b.WriteString("var dgaBigram = [dgaSymbols * dgaSymbols]float32{\n")
	for prev := range symbols {
		for next := range symbols {
			fmt.Fprintf(&b, "%.4f,", model[prev][next])
			if next%8 == 7 {
				b.WriteString("\n")
			}
		}
		b.WriteString("\n")
	}
	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("dga_model.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// usable reports whether label has only the model's symbols and isn't
// Punycode.
func usable(label string) bool {
	if label == "" || strings.HasPrefix(label, "xn--") {
		return false
	}
	for i := range len(label) {
		if symbol(label[i]) < 0 {
			return false
		}
	}
	return true
}

// train returns log2 P(next | prev) from labels' bigrams, with additive
// smoothing.
func train(labels []string) (model [symbols][symbols]float64) {
	var counts [symbols][symbols]float64
	for _, label := range labels {
		prev := boundary
		for i := range len(label) {
			s := symbol(label[i])
			counts[prev][s]++
			prev = s
		}
		counts[prev][boundary]++
	}
	for prev := range symbols {
		total := 0.0
		for next := range symbols {
			if next == boundary && prev == boundary {
				continue // empty labels
			}
			total += counts[prev][next] + smoothing
		}
		for next := range symbols {
			p := (counts[prev][next] + smoothing) / total
			if next == boundary && prev == boundary {
				p = 1 / total // unused
			}
			model[prev][next] = math.Log2(p)
		}
	}
	return model
}

// corpus returns the registrable labels of the domains in path, one per
// line, skipping comments.
func corpus(path string) []string {
	f, err := os.Open(path)
	if err != nil {
		log.Fatal(err)
	}
	defer f.Close()

	var labels []string
	s := bufio.NewScanner(f)
	for s.Scan() {
		line := strings.ToLower(strings.TrimSpace(s.Text()))
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		if label := registrableLabel(line); label != "" {
			labels = append(labels, label)
		}
	}
	if err := s.Err(); err != nil {
		log.Fatal(err)
	}
	return labels
}

// registrableLabel returns the label of name's registrable domain under
// the ICANN section of the Public Suffix List, as filter.Registrable
// finds it, or "".
func registrableLabel(name string) string {
	labels := strings.Split(name, ".")
	for i := 1; i < len(labels); i++ {
		suffix := strings.Join(labels[i:], ".")
		if ps, icann := publicsuffix.PublicSuffix(suffix); icann && ps == suffix {
			return labels[i-1]
		}
	}
	return ""
}

// brandNames returns the brand names in brands.go.
func brandNames(path string) []string {
	src, err := os.ReadFile(path)
	if err != nil {
		log.Fatal(err)
	}
	var names []string
	for _, m := range regexp.MustCompile(`\{name: "([a-z0-9]+)"`).FindAllSubmatch(src, -1) {
		names = append(names, string(m[1]))
	}
	return names
}
